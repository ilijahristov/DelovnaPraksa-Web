-- Initial schema.

CREATE TABLE users (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL,
  email         text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role          text NOT NULL DEFAULT 'STUDENT' CHECK (role IN ('STUDENT', 'PROFESSOR')),
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE courses (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        text NOT NULL UNIQUE,
  title       text NOT NULL,
  description text NOT NULL DEFAULT '',
  -- A professor who still owns courses cannot be deleted.
  owner_id    integer NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX courses_owner_id_idx ON courses (owner_id);

-- Deleting a user or a course removes the enrollments.
CREATE TABLE enrollments (
  user_id    integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  course_id  integer NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, course_id)
);
CREATE INDEX enrollments_course_id_idx ON enrollments (course_id);

-- Deleting a course removes its materials.
CREATE TABLE materials (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  integer NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  title      text NOT NULL,
  url        text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX materials_course_id_idx ON materials (course_id);
